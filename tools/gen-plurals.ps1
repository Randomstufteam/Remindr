# Generates src\Remindr\Services\PluralRules.Generated.cs from the pinned CLDR plural rules (tools\cldr\plurals.xml, CLDR 46.1).
#
# Only the cardinal rules for WHOLE numbers are generated: reminder counts are integers, so in a CLDR rule n and i are the number and
# v, w, f, t, e and c are all 0. Conditions that become constant are folded away (e.g. Czech "many" is for fractions only and is dropped).
#
# Run from the repo root (a normal PowerShell may need -ExecutionPolicy Bypass):
#   powershell -ExecutionPolicy Bypass -File tools\gen-plurals.ps1
# To move to a newer CLDR, replace tools\cldr\plurals.xml (from unicode-org/cldr, common/supplemental/plurals.xml), run this script,
# and run the tests: PluralRulesCldrTests re-checks every integer sample of that file against the generated code.

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$source = Join-Path $root 'tools\cldr\plurals.xml'
$target = Join-Path $root 'src\Remindr\Services\PluralRules.Generated.cs'

$settings = New-Object System.Xml.XmlReaderSettings
$settings.DtdProcessing = 'Ignore'
$settings.XmlResolver = $null
$reader = [System.Xml.XmlReader]::Create($source, $settings)
$xml = New-Object System.Xml.XmlDocument
$xml.Load($reader)
$reader.Close()

# One relation, e.g. "i % 10 = 2..4,9" -> a C# expression, "true" or "false".
function ConvertRelation([string]$text) {
    $m = [regex]::Match($text.Trim(), '^([nivwftec])(?: % (\d+))? (!=|=) (.+)$')
    if (-not $m.Success) { throw "Cannot parse relation: $text" }
    $operand = $m.Groups[1].Value
    $mod = $m.Groups[2].Value
    $negate = $m.Groups[3].Value -eq '!='
    $items = @($m.Groups[4].Value.Split(",") | ForEach-Object {
        $r = [regex]::Match($_.Trim(), '^(\d+)\.\.(\d+)$')
        if ($r.Success) { , @([long]$r.Groups[1].Value, [long]$r.Groups[2].Value) }
        else { , @([long]$_.Trim(), [long]$_.Trim()) }
    })
    if ($operand -in @('n', 'i')) {
        $x = if ($mod) { "(n % $mod)" } else { 'n' }
        $parts = $items | ForEach-Object {
            if ($_[0] -eq $_[1]) { "$x == $($_[0])" } else { "($x >= $($_[0]) && $x <= $($_[1]))" }
        }
        $expr = ($parts -join ' || ')
        if ($negate) { return "!($expr)" }
        if (@($parts).Count -gt 1) { return "($expr)" }
        return $expr
    }
    # v, w, f, t, e, c are 0 for a whole number.
    $inside = $false
    foreach ($it in $items) { if ($it[0] -le 0 -and $it[1] -ge 0) { $inside = $true } }
    if ($negate) { $inside = -not $inside }
    if ($inside) { return 'true' } else { return 'false' }
}

# "a and b or c" -> C# expression, "true" (always) or "false" (never).
function ConvertCondition([string]$text) {
    $orGroups = @()
    foreach ($orPart in ($text -split ' or ')) {
        $terms = @()
        $never = $false
        foreach ($rel in ($orPart -split ' and ')) {
            $c = ConvertRelation $rel
            if ($c -eq 'false') { $never = $true; break }
            if ($c -ne 'true') { $terms += $c }
        }
        if ($never) { continue }
        if ($terms.Count -eq 0) { return 'true' }
        if ($terms.Count -eq 1) { $orGroups += $terms[0] } else { $orGroups += '(' + ($terms -join ' && ') + ')' }
    }
    if ($orGroups.Count -eq 0) { return 'false' }
    return ($orGroups -join ' || ')
}

$sb = New-Object System.Text.StringBuilder
$cases = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('// <auto-generated>')
[void]$sb.AppendLine('// Generated by tools/gen-plurals.ps1 from tools/cldr/plurals.xml (Unicode CLDR 46.1, cardinal rules, whole numbers only).')
[void]$sb.AppendLine('// Do not edit by hand: change the script or the pinned CLDR file and run it again.')
[void]$sb.AppendLine('// CLDR data is Copyright (c) Unicode, Inc., used under the Unicode License v3 (see THIRD-PARTY-NOTICES.md).')
[void]$sb.AppendLine('// </auto-generated>')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('#nullable enable')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('namespace Remindr.Services;')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('public static partial class PluralRules')
[void]$sb.AppendLine('{')

$index = 0
$groups = $xml.SelectNodes("//plurals[@type='cardinal']/pluralRules")
foreach ($g in $groups) {
    $index++
    $locales = $g.GetAttribute('locales').Split(' ', [StringSplitOptions]::RemoveEmptyEntries) | Where-Object { $_ -ne 'root' }
    if (-not $locales) { continue }
    $name = "Rule$index"
    foreach ($l in $locales) { [void]$cases.AppendLine("            case `"$l`":") }
    [void]$cases.AppendLine("                return $name(n);")

    [void]$sb.AppendLine("    // $($locales -join ' ')")
    [void]$sb.AppendLine("    private static string $name(long n)")
    [void]$sb.AppendLine('    {')
    $done = $false
    foreach ($rule in $g.SelectNodes('pluralRule')) {
        $count = $rule.GetAttribute('count')
        if ($count -eq 'other') { continue }
        $cond = ($rule.InnerText -split '@')[0].Trim()
        $cs = ConvertCondition $cond
        $cat = (Get-Culture).TextInfo.ToTitleCase($count)
        if ($cs -eq 'false') { continue }
        if ($cs -eq 'true') { [void]$sb.AppendLine("        return `"$cat`";"); $done = $true; break }
        [void]$sb.AppendLine("        if ($cs) return `"$cat`";")
    }
    if (-not $done) { [void]$sb.AppendLine('        return "Other";') }
    [void]$sb.AppendLine('    }')
    [void]$sb.AppendLine('')
}

[void]$sb.AppendLine('    /// <summary>The CLDR category of a whole, non-negative number for a CLDR locale key ("ru", "pt_PT"), or null when CLDR has no rule for it (then it is "Other").</summary>')
[void]$sb.AppendLine('    private static string? Generated(string locale, long n)')
[void]$sb.AppendLine('    {')
[void]$sb.AppendLine('        switch (locale)')
[void]$sb.AppendLine('        {')
[void]$sb.Append($cases.ToString())
[void]$sb.AppendLine('            default:')
[void]$sb.AppendLine('                return null;')
[void]$sb.AppendLine('        }')
[void]$sb.AppendLine('    }')
[void]$sb.AppendLine('}')

[System.IO.File]::WriteAllText($target, $sb.ToString().Replace("`r`n", "`n"), (New-Object System.Text.UTF8Encoding($false)))
Write-Host "Wrote $target ($index rule groups)"
